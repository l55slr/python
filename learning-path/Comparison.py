#Comparison Operators
"""
< "less than"
> "greater than"
<= "less than or equal to"
>= "greater than or equal to"
== "equal to"
!= "not equal to"
"""
#If Statements
if 2 > 1:
    print("2 is greater than 1")

#If-Else Statements
if 2 < 1:
    print("2 is less than 1")
else:
    print("2 is not less than 1")